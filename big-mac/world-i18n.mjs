export const language = () => Object.hasOwn(copy,document.documentElement.lang) ? document.documentElement.lang : 'pl';
export const locale = () => ({pl:'pl-PL',en:'en-GB',it:'it-IT'}[language()]);
export function t(key,values={}) {
  let result=copy[language()][key] || key;
  for (const [name,value] of Object.entries(values)) result=result.replaceAll(`{${name}}`,value);
  return result;
}
export function applyMessages() {
  document.querySelectorAll('[data-msg]').forEach(node => {node.textContent=t(node.dataset.msg);});
  document.querySelectorAll('[data-msg-aria]').forEach(node => {node.setAttribute('aria-label',t(node.dataset.msgAria));});
}
