export function t(key, values = {}) {
  let value = copy[document.documentElement.lang]?.[key] || key;
  for (const [name, replacement] of Object.entries(values)) value = value.replaceAll(`{${name}}`,replacement);
  return value;
}
const walker = document.createTreeWalker(document.querySelector('main'),NodeFilter.SHOW_TEXT);
const staticNodes = [];
while (walker.nextNode()) {
  const node = walker.currentNode;
  const original = node.textContent;
  if (Object.hasOwn(copy.en,original.trim())) staticNodes.push({node,original});
}
const ariaNodes = [...document.querySelectorAll('main [aria-label],.skip-link')].map(node => ({node,original:node.getAttribute('aria-label'),text:node.classList.contains('skip-link') ? node.textContent : null}));
export function translateStaticContent() {
  for (const {node,original} of staticNodes) node.textContent = original.replace(original.trim(),t(original.trim()));
  for (const {node,original,text} of ariaNodes) {
    if (original) node.setAttribute('aria-label',t(original));
    if (text) node.textContent = t(text);
  }
}
